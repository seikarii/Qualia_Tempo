/// # Responsibility
/// Enumerates the types of audio events for the frontend AudioEngineService.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, JsonSchema, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum AudioEventType {
    PlaySfx,
    StopSfx,
    PlayMusic,
    StopMusic,
    Crossfade,
    VolumeChange,
    PitchShift,
    ApplyFilter,
    TriggerStinger,
    SyncBeat,
}

/// # Responsibility
/// Enumerates audio filter types.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, JsonSchema, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum FilterType {
    Lowpass,
    Highpass,
    Bandpass,
    Reverb,
    Delay,
    Distortion,
}

/// # Responsibility
/// Defines playback parameters for an audio event.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct AudioEventParameters {
    pub volume: Option<f32>,
    pub pitch: Option<f32>,
    pub pan: Option<f32>,
    pub fade_in_sec: Option<f64>,
    pub fade_out_sec: Option<f64>,
    pub loop_playback: Option<bool>,
    pub priority: Option<f32>,
}

/// # Responsibility
/// Defines audio filter settings for an audio event.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct AudioFilterSettings {
    #[serde(rename = "type")]
    pub filter_type: Option<FilterType>,
    pub frequency: Option<f32>,
    pub resonance: Option<f32>,
    pub wet_dry_mix: Option<f32>,
}

/// # Responsibility
/// Defines spatial audio positioning data.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct SpatialData {
    pub position: Option<crate::utils::Vec3>,
    pub max_distance: Option<f32>,
    pub rolloff_factor: Option<f32>,
}

/// # Responsibility
/// Defines a command for the frontend audio engine to execute.
///
/// ---
///
/// These events are generated by frontend services and processed by
/// AudioEngineService to control playback, mixing, and effects.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct AudioEvent {
    pub id: String,
    #[serde(rename = "type")]
    pub event_type: AudioEventType,
    pub timestamp: f64,
    pub audio_clip_id: Option<String>,
    pub layer_id: Option<String>,
    pub parameters: Option<AudioEventParameters>,
    pub filter_settings: Option<AudioFilterSettings>,
    pub spatial_data: Option<SpatialData>,
    pub trigger_condition: Option<crate::contracts::combat_data::QualiaThreshold>,
}

/// # Responsibility
/// Enumerates audio layer types for mixing organization.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, JsonSchema, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum AudioLayerType {
    Music,
    Sfx,
    Ambient,
    Voice,
    Ui,
}

/// # Responsibility
/// Represents an active audio source within a mixing layer.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct ActiveAudioSource {
    pub source_id: String,
    pub audio_clip_id: String,
    pub start_time: f64,
    pub volume: f32,
    pub is_looping: bool,
}

/// # Responsibility
/// Represents an effect applied to an audio layer.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct LayerEffect {
    pub effect_id: String,
    #[serde(rename = "type")]
    pub effect_type: String, // e.g., "compressor", "eq"
    pub enabled: bool,
    pub parameters: Option<std::collections::HashMap<String, f32>>,
}

/// # Responsibility
/// Defines a complete mixing layer with sources and effects.
///
/// ---
///
/// Used by frontend AudioEngineService to organize and process audio.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct AudioLayerFull {
    pub id: String,
    pub name: String,
    #[serde(rename = "type")]
    pub layer_type: AudioLayerType,
    pub volume: f32,
    pub muted: bool,
    pub solo: bool,
    pub active_sources: Vec<ActiveAudioSource>,
    pub effects: Vec<LayerEffect>,
    pub qualia_modulation: Option<std::collections::HashMap<String, bool>>,
}

