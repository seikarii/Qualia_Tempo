//! # Responsibility
//! Defines audio system contracts per MUSIC.RUST.md specifications.
//!
//! ---
//!
//! Contains HarmonyMap, InstrumentPatch, and audio event structures
//! that bridge the Harmony Engine (backend) and Performance Engine (frontend).

use crate::utils::Vec2;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// # Responsibility
/// Defines a single harmonic region within a song's timeline.
///
/// ---
///
/// Used by HarmonyAnalysisService to map song timeline to musical theory.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct HarmonicContext {
    pub start_time_sec: f64,
    pub end_time_sec: f64,
    pub chord: String, // e.g., "Am7", "G", "Cmaj7"
    pub scale: Vec<String>, // e.g., ["A", "B", "C", "D", "E", "F", "G"]
}

/// # Responsibility
/// Contains the complete musical theory analysis of a song.
///
/// ---
///
/// This map is the "ruleset" for all generative music.
/// Generated by HarmonyAnalysisService, consumed by GameLogicService.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct HarmonyMap {
    pub song_id: String,
    pub key_signature: String, // e.g., "C Major"
    pub time_signature: (u8, u8), // e.g., (4, 4)
    pub bpm: f32,
    pub progression: Vec<HarmonicContext>,
}

/// # Responsibility
/// Defines synthesizer parameters for procedural sound generation.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct SynthParameters {
    pub oscillator1_type: String, // "sine", "square", "sawtooth"
    pub oscillator2_type: Option<String>,
    pub filter_cutoff: f32,
    pub adsr_attack: f32,
    pub adsr_decay: f32,
    pub adsr_sustain: f32,
    pub adsr_release: f32,
}

impl Default for SynthParameters {
    fn default() -> Self {
        Self {
            oscillator1_type: "sine".to_string(),
            oscillator2_type: None,
            filter_cutoff: 1000.0,
            adsr_attack: 0.01,
            adsr_decay: 0.1,
            adsr_sustain: 0.5,
            adsr_release: 0.3,
        }
    }
}

/// # Responsibility
/// Enumerates the type of instrument patch (sampler or synthesizer).
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(tag = "type", rename_all = "camelCase")]
pub enum PatchType {
    /// Sample-based instrument (loads .wav files)
    Sampler {
        sample_map_url: String, // URL to JSON mapping MIDI notes to .wav files
    },
    /// Synthesized instrument (procedural generation)
    Synth { parameters: SynthParameters },
}

/// # Responsibility
/// Defines a playable instrument, either sample-based or synthesized.
///
/// ---
///
/// Player and Boss will have a collection of these assigned per level.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct InstrumentPatch {
    pub id: String,
    pub name: String,
    pub patch_type: PatchType,
}

/// # Responsibility
/// Represents an audio layer in the 8D audio mix.
///
/// ---
///
/// Each layer can be individually controlled (volume, pan, effects).
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct AudioLayer {
    pub id: String,
    pub name: String,
    pub volume: f32, // 0.0 to 1.0
    pub is_muted: bool,
    pub spatial_position: Option<Vec2>, // For 8D audio
}

/// # Responsibility
/// Represents complete song data loaded from configuration.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct SongData {
    pub id: String,
    pub title: String,
    pub artist: String,
    pub duration_sec: f64,
    pub audio_url: String,
    pub harmony_map: HarmonyMap,
    pub layers: Vec<AudioLayer>,
}

